/** Seed or idempotently refresh the showcase-v02 mission inside OverdriveStore. */
export function seedShowcaseMission(store, options = {}) {
  if (!store || typeof store.upsertShowcase !== "function") {
    throw new Error("seedShowcaseMission requires an OverdriveStore instance.");
  }
  const spec = buildShowcaseSpec(options);
  const { mission, created } = store.upsertShowcase(spec, options);
  if (typeof store.listRsiCandidates === "function") {
    seedShowcaseRsiIfEmpty(store, { repoRoot: options.repoRoot || mission.repoRoot });
  }
  return {
    ok: true,
    schemaVersion: SCHEMA_VERSION,
    missionId: mission.id,
    slug: mission.slug,
    fixtureVersion: spec.fixtureVersion,
    created,
    mission,
  };
}
